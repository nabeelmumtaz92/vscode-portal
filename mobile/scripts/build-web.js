#!/usr/bin/env node
// Packs the phone UI (extension/web) into one HTML string the app ships with, so it opens instantly and
// doesn't depend on a website. Run before building the app: npm run web.
const fs = require('fs');
const path = require('path');

const WEB = path.join(__dirname, '..', '..', 'extension', 'web');
const OUT = path.join(__dirname, '..', 'src', 'webBundle.ts');
const read = (f) => fs.readFileSync(path.join(WEB, f), 'utf8');

if (!fs.existsSync(path.join(WEB, 'editor.bundle.js'))) {
  console.error('extension/web/editor.bundle.js is missing: run "npm run build" in extension/ first.');
  process.exit(1);
}

let html = read('index.html')
  // The app has its own icon; no web manifest
  .replace(/<link rel="(manifest|icon|apple-touch-icon)"[^>]*>\n?/g, '')
  .replace('<link rel="stylesheet" href="style.css">', () => `<style>\n${read('style.css')}\n</style>`)
  // A script can't contain "</script" inside an inline <script>
  .replace(/<script src="([^"]+)"><\/script>/g, (_, f) => `<script>\n${read(f).replace(/<\/script/gi, '<\\/script')}\n</script>`);

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/build-web.js from extension/web. Don't edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`Wrote src/webBundle.ts (${Math.round(html.length / 1024)} KB)`);
